-- 1. CATALOGO: FORMAS DE PAGO (SAT)
CREATE TABLE cat_forma_pago (
    id_forma_pago   VARCHAR2(5)   PRIMARY KEY,
    descripcion     VARCHAR2(100) NOT NULL,
    activo          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT chk_fp_activo CHECK (activo IN (0, 1))
);

-- 2. CATALOGO: METODOS DE PAGO (SAT)
CREATE TABLE cat_metodo_pago (
    id_metodo_pago  VARCHAR2(5)   PRIMARY KEY,
    descripcion     VARCHAR2(100) NOT NULL,
    activo          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT chk_mp_activo CHECK (activo IN (0, 1))
);

-- 3. CATALOGO: REGIMENES FISCALES (SAT)
CREATE TABLE cat_regimen_fiscal (
    id_regimen_fiscal VARCHAR2(5)   PRIMARY KEY,
    descripcion       VARCHAR2(150) NOT NULL,
    aplica_fisica     NUMBER(1)     DEFAULT 1 NOT NULL,
    aplica_moral      NUMBER(1)     DEFAULT 1 NOT NULL,
    activo            NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT chk_rf_fisica CHECK (aplica_fisica IN (0, 1)),
    CONSTRAINT chk_rf_moral  CHECK (aplica_moral  IN (0, 1)),
    CONSTRAINT chk_rf_activo CHECK (activo        IN (0, 1))
);

-- 4. CATALOGO: USOS DE CFDI (SAT)
CREATE TABLE cat_uso_cfdi (
    id_uso_cfdi     VARCHAR2(5)   PRIMARY KEY,
    descripcion     VARCHAR2(150) NOT NULL,
    activo          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT chk_uc_activo CHECK (activo IN (0, 1))
);

-- 5. TABLA: USUARIOS VINCULADOS A AMAZON COGNITO (SIN CONTRASENAS EN ORACLE)
CREATE TABLE usuarios (
    id_usuario      NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cognito_sub     VARCHAR2(64)  NOT NULL UNIQUE,
    email           VARCHAR2(120) NOT NULL UNIQUE,
    nombre          VARCHAR2(120) NOT NULL,
    rol             VARCHAR2(30)  DEFAULT 'FACTURADOR' NOT NULL,
    activo          NUMBER(1)     DEFAULT 1 NOT NULL,
    fecha_creacion  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ultimo_acceso   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT chk_usr_activo CHECK (activo IN (0, 1)),
    CONSTRAINT chk_usr_rol    CHECK (rol IN ('ADMIN_ACADEMICO', 'FACTURADOR', 'AUDITOR'))
);

-- 6. TABLA: CLIENTES / RECEPTORES FISCALES
CREATE TABLE clientes (
    id_cliente        NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfc               VARCHAR2(13)  NOT NULL UNIQUE,
    razon_social      VARCHAR2(200) NOT NULL,
    codigo_postal     VARCHAR2(5)   NOT NULL,
    id_regimen_fiscal VARCHAR2(5)   NOT NULL,
    id_uso_cfdi       VARCHAR2(5)   NOT NULL,
    email             VARCHAR2(120) NOT NULL,
    fecha_registro    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    activo            NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT fk_cli_regimen  FOREIGN KEY (id_regimen_fiscal) REFERENCES cat_regimen_fiscal(id_regimen_fiscal),
    CONSTRAINT fk_cli_usocfdi  FOREIGN KEY (id_uso_cfdi)       REFERENCES cat_uso_cfdi(id_uso_cfdi),
    CONSTRAINT chk_cli_activo  CHECK (activo IN (0, 1))
);

-- 7. TABLA: CABECERA DE FACTURAS
CREATE TABLE facturas (
    id_factura         NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_fiscal_uuid  VARCHAR2(36)  UNIQUE,
    serie              VARCHAR2(10)  DEFAULT 'A' NOT NULL,
    folio              NUMBER        NOT NULL UNIQUE,
    rfc_emisor         VARCHAR2(13)  NOT NULL,
    id_cliente         NUMBER        NOT NULL,
    id_usuario_creador NUMBER        NOT NULL,
    id_forma_pago      VARCHAR2(5)   NOT NULL,
    id_metodo_pago     VARCHAR2(5)   NOT NULL,
    direccion_fiscal   VARCHAR2(255) NOT NULL,
    comentarios        VARCHAR2(400),
    subtotal           NUMBER(14,2)  DEFAULT 0.00 NOT NULL,
    total_impuestos    NUMBER(14,2)  DEFAULT 0.00 NOT NULL,
    total              NUMBER(14,2)  DEFAULT 0.00 NOT NULL,
    moneda             VARCHAR2(3)   DEFAULT 'MXN' NOT NULL,
    estado             VARCHAR2(20)  DEFAULT 'PENDIENTE' NOT NULL,
    fecha_emision      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_timbrado     TIMESTAMP,
    CONSTRAINT fk_fac_cliente    FOREIGN KEY (id_cliente)         REFERENCES clientes(id_cliente),
    CONSTRAINT fk_fac_usuario    FOREIGN KEY (id_usuario_creador) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_fac_formapago  FOREIGN KEY (id_forma_pago)      REFERENCES cat_forma_pago(id_forma_pago),
    CONSTRAINT fk_fac_metodopago FOREIGN KEY (id_metodo_pago)     REFERENCES cat_metodo_pago(id_metodo_pago),
    CONSTRAINT chk_fac_subtotal  CHECK (subtotal >= 0),
    CONSTRAINT chk_fac_total     CHECK (total >= subtotal),
    CONSTRAINT chk_fac_estado    CHECK (estado IN ('PENDIENTE', 'TIMBRADA', 'CANCELADA'))
);

-- 8. TABLA: DETALLE DE FACTURA (REFERENCIA A DYNAMODB ListServices.id_service)
CREATE TABLE factura_detalles (
    id_detalle         NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura         NUMBER        NOT NULL,
    id_servicio_dynamo VARCHAR2(50)  NOT NULL,
    descripcion_item   VARCHAR2(200) NOT NULL,
    clave_sat_producto VARCHAR2(10)  DEFAULT '81112100' NOT NULL,
    clave_sat_unidad   VARCHAR2(5)   DEFAULT 'E48' NOT NULL,
    cantidad           NUMBER(10,2)  DEFAULT 1 NOT NULL,
    precio_unitario    NUMBER(14,2)  NOT NULL,
    importe            NUMBER(14,2)  NOT NULL,
    descuento          NUMBER(14,2)  DEFAULT 0.00 NOT NULL,
    CONSTRAINT fk_det_factura FOREIGN KEY (id_factura) REFERENCES facturas(id_factura) ON DELETE CASCADE,
    CONSTRAINT chk_det_cant    CHECK (cantidad > 0),
    CONSTRAINT chk_det_precio  CHECK (precio_unitario >= 0),
    CONSTRAINT chk_det_importe CHECK (importe >= 0)
);

-- 9. TABLA: IMPUESTOS POR DETALLE (IVA 16% TRASLADADO)
CREATE TABLE factura_impuestos (
    id_impuesto  NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle   NUMBER       NOT NULL,
    impuesto     VARCHAR2(5)  DEFAULT '002' NOT NULL,
    tipo_factor  VARCHAR2(10) DEFAULT 'Tasa' NOT NULL,
    tasa_cuota   NUMBER(6,4)  DEFAULT 0.1600 NOT NULL,
    base         NUMBER(14,2) NOT NULL,
    importe      NUMBER(14,2) NOT NULL,
    CONSTRAINT fk_imp_detalle FOREIGN KEY (id_detalle) REFERENCES factura_detalles(id_detalle) ON DELETE CASCADE,
    CONSTRAINT chk_imp_base    CHECK (base >= 0),
    CONSTRAINT chk_imp_importe CHECK (importe >= 0)
);

-- 10. TABLA: BITACORA DE AUDITORIA Y TRAZABILIDAD
CREATE TABLE bitacora_facturacion (
    id_evento    NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura   NUMBER,
    accion       VARCHAR2(50)  NOT NULL,
    descripcion  VARCHAR2(400) NOT NULL,
    ip_origen    VARCHAR2(45),
    usuario      VARCHAR2(120) DEFAULT USER NOT NULL,
    fecha_evento TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_bit_factura FOREIGN KEY (id_factura) REFERENCES facturas(id_factura) ON DELETE SET NULL
);

-- SECUENCIA E INDICES DE RENDIMIENTO
CREATE SEQUENCE seq_folio_factura START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE INDEX idx_fac_cliente ON facturas(id_cliente);
CREATE INDEX idx_fac_estado  ON facturas(estado);
CREATE INDEX idx_det_factura ON factura_detalles(id_factura);
CREATE INDEX idx_imp_detalle ON factura_impuestos(id_detalle);
CREATE INDEX idx_bit_factura ON bitacora_facturacion(id_factura);

